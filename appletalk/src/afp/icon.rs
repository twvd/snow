/// The Volume Icon and Mask field of FPGetSrvrInfo: the icon's 128 bytes,
/// then the mask's (Inside AppleTalk, 2nd edition, chapter 13)
pub(super) fn volume_icon() -> Vec<u8> {
    ICON.iter()
        .chain(MASK.iter())
        .flat_map(|row| row.to_be_bytes())
        .collect()
}
